/**
 * Minimal .env loader — zero dependencies.
 *
 * Reads the root .env file and sets process.env variables that are not
 * already defined by the shell. Only handles KEY=VALUE lines; comments
 * and blank lines are skipped.
 */

import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { dirname } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));

export function loadEnv(): void {
  // Walk up to the monorepo root (two levels from eval/src/)
  const envPath = join(__dirname, '..', '..', '.env');
  if (!existsSync(envPath)) return;

  const content = readFileSync(envPath, 'utf-8');
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq < 0) continue;
    const key = trimmed.slice(0, eq).trim();
    const value = trimmed.slice(eq + 1).trim();
    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}
